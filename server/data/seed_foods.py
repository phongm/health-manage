def n(
    energy: float,
    protein: float,
    fat: float,
    cho: float,
    fiber: float = 0.0,
    sodium: float = 0.0,
    sugar: float | None = None,
) -> dict:
    data = {
        "energy_kcal": energy,
        "protein_g": protein,
        "fat_g": fat,
        "cho_g": cho,
        "fiber_g": fiber,
        "sodium_mg": sodium,
    }
    if sugar is not None:
        data["sugar_g"] = sugar
    return data


